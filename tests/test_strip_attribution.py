import importlib.util
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("strip_attribution", ROOT / ".github/scripts/strip_attribution.py")
strip = importlib.util.module_from_spec(spec)
spec.loader.exec_module(strip)


class CleanTests(unittest.TestCase):
    def test_pr_body_footers_are_removed(self):
        body = ("Fixes #55.\n\n## Not verified\n\n- The full client.\n\n"
                "🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\n"
                "https://claude.ai/code/session_01PsJaqgopd8Zo6WwWmBkyQL\n\n---\n"
                "_Generated by [Claude Code](https://claude.ai/code/session_01PsJaqgopd8Zo6WwWmBkyQL)_")
        self.assertEqual(strip.clean(body), "Fixes #55.\n\n## Not verified\n\n- The full client.")

    def test_comment_footer_is_removed(self):
        body = "Thanks!\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        self.assertEqual(strip.clean(body), "Thanks!")

    def test_commit_trailers_are_removed(self):
        body = ("Fix it\n\nBody.\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n"
                "Claude-Session: https://claude.ai/code/session_01Abc")
        self.assertEqual(strip.clean(body), "Fix it\n\nBody.")

    def test_text_without_attribution_is_returned_unchanged(self):
        for body in ("", None, "Plain\n\n---\n\nrule kept\n", "Mentions Claude Code in a sentence.\n"):
            self.assertIs(strip.clean(body), body)

    def test_untrusted_authors_are_never_edited(self):
        calls = []
        item = {"author_association": "NONE", "body": "x\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"}
        with patch.object(strip, "api", lambda *args: calls.append(args)):
            self.assertFalse(strip.fix(item, "/edit"))
            item["author_association"] = "MEMBER"
            self.assertTrue(strip.fix(item, "/edit"))
        self.assertEqual(calls, [("PATCH", "/edit", {"body": "x"})])


class CommitCheckTests(unittest.TestCase):
    def test_only_attributed_commits_fail(self):
        with tempfile.TemporaryDirectory() as tmp:
            env = {**os.environ, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t",
                   "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@t"}
            git = lambda *a: subprocess.run(["git", "-C", tmp, *a], env=env, check=True,
                                            capture_output=True, text=True).stdout.strip()
            git("init", "-q")
            git("commit", "-q", "--allow-empty", "-m", "base")
            base = git("rev-parse", "HEAD")
            git("commit", "-q", "--allow-empty", "-m", "clean change")
            cwd = os.getcwd()
            os.chdir(tmp)
            try:
                self.assertEqual(strip.commits(base + "..HEAD"), 0)
                git("commit", "-q", "--allow-empty", "-m",
                    "change\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>")
                self.assertEqual(strip.commits(base + "..HEAD"), 1)
            finally:
                os.chdir(cwd)


if __name__ == "__main__":
    unittest.main()
