import importlib.util
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("strip_attribution", ROOT / ".github/scripts/strip_attribution.py")
strip = importlib.util.module_from_spec(spec)
spec.loader.exec_module(strip)


class CleanTests(unittest.TestCase):
    def test_pr_body_footers_are_removed(self):
        body = ("Fixes #55.\n\n## Not verified\n\n- The full client.\n\n"
                "🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\n"
                "https://claude.ai/code/session_01PsJaqgopd8Zo6WwWmBkyQL\n\n---\n"
                "_Generated by [Claude Code](https://claude.ai/code/session_01PsJaqgopd8Zo6WwWmBkyQL)_")
        self.assertEqual(strip.clean(body), "Fixes #55.\n\n## Not verified\n\n- The full client.")

    def test_comment_footer_is_removed(self):
        body = "Thanks!\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        self.assertEqual(strip.clean(body), "Thanks!")

    def test_commit_trailers_are_removed(self):
        body = ("Fix it\n\nBody.\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n"
                "Claude-Session: https://claude.ai/code/session_01Abc")
        self.assertEqual(strip.clean(body), "Fix it\n\nBody.")

    def test_text_without_attribution_is_returned_unchanged(self):
        for body in ("", None, "Plain\n\n---\n\nrule kept\n", "Mentions Claude Code in a sentence.\n"):
            self.assertIs(strip.clean(body), body)

    def test_a_rule_unrelated_to_the_footer_is_kept(self):
        body = "before\n_Generated by [Claude Code](https://claude.ai/code)_\nafter\n\n---"
        self.assertEqual(strip.clean(body), "before\nafter\n\n---")

    def fake_api(self, current, calls, fail=None):
        def api(method, path, body=None):
            calls.append((method, path, body))
            if method == "PATCH" and fail:
                raise strip.urllib.error.HTTPError(path, fail, "denied", {}, None)
            return dict(current), None
        return api

    def test_untrusted_authors_are_never_edited(self):
        calls = []
        footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        item = {"author_association": "NONE", "body": "x" + footer}
        with patch.object(strip, "api", self.fake_api(item, calls)):
            self.assertFalse(strip.fix(item, "/edit"))
            self.assertEqual(calls, [])
            item["author_association"] = "MEMBER"
            self.assertTrue(strip.fix(item, "/edit"))
        self.assertEqual(calls, [("GET", "/edit", None), ("PATCH", "/edit", {"body": "x"})])

    def test_a_member_listed_as_contributor_is_trusted_by_write_access(self):
        calls = []
        footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        item = {"author_association": "CONTRIBUTOR", "user": {"login": "member", "type": "User"},
                "body": "x" + footer}
        def api(method, path, body=None):
            calls.append((method, path, body))
            if path.endswith("/collaborators/member/permission"):
                return {"permission": "admin"}, None
            if path.endswith("/collaborators/outsider/permission"):
                raise strip.urllib.error.HTTPError(path, 404, "not a collaborator", {}, None)
            return dict(item), None
        with patch.dict(os.environ, {"GITHUB_REPOSITORY": "o/r"}), \
             patch.object(strip, "api", api), patch.object(strip, "_permissions", {}):
            self.assertTrue(strip.fix(item, "/edit"))
            outsider = dict(item, user={"login": "outsider", "type": "User"})
            self.assertFalse(strip.fix(outsider, "/edit2"))
            bot = dict(item, user={"login": "codex[bot]", "type": "Bot"})
            self.assertFalse(strip.fix(bot, "/edit3"))
        self.assertIn(("PATCH", "/edit", {"body": "x"}), calls)
        self.assertFalse(any(c[1] in ("/edit2", "/edit3") for c in calls))

    def test_the_current_body_is_cleaned_not_the_event_payload(self):
        calls = []
        footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        stale = {"author_association": "OWNER", "body": "old" + footer}
        current = {"author_association": "OWNER", "body": "newer edit" + footer}
        with patch.object(strip, "api", self.fake_api(current, calls)):
            self.assertTrue(strip.fix(stale, "/edit"))
        self.assertEqual(calls[-1], ("PATCH", "/edit", {"body": "newer edit"}))

    def test_read_only_token_is_a_notice_not_a_failure(self):
        calls = []
        item = {"author_association": "OWNER", "body": "x\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"}
        with patch.object(strip, "api", self.fake_api(item, calls, fail=403)):
            self.assertFalse(strip.fix(item, "/edit"))
        with patch.object(strip, "api", self.fake_api(item, calls, fail=500)):
            with self.assertRaises(strip.urllib.error.HTTPError):
                strip.fix(item, "/edit")


class CommitCheckTests(unittest.TestCase):
    def test_only_attributed_commits_fail(self):
        with tempfile.TemporaryDirectory() as tmp:
            env = {**os.environ, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t",
                   "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@t"}
            git = lambda *a: subprocess.run(["git", "-C", tmp, *a], env=env, check=True,
                                            capture_output=True, text=True).stdout.strip()
            git("init", "-q")
            git("commit", "-q", "--allow-empty", "-m", "base")
            base = git("rev-parse", "HEAD")
            git("commit", "-q", "--allow-empty", "-m", "clean change")
            cwd = os.getcwd()
            os.chdir(tmp)
            try:
                self.assertEqual(strip.commits(base + "..HEAD"), 0)
                git("commit", "-q", "--allow-empty", "-m",
                    "change\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>")
                self.assertEqual(strip.commits(base + "..HEAD"), 1)
            finally:
                os.chdir(cwd)


if __name__ == "__main__":
    unittest.main()
