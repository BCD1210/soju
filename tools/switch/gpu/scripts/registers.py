"""Extract method facts from pinned NVIDIA public headers downloaded to target/reference.
Never runs as part of a build. See SOURCES.md and LICENSE.nvidia.
"""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
revision = '9fdf5c4062007929d9f4e6cbad9c9771fe61b880'
specs = [('b197','3d',0xb197), ('a140','inline-to-memory',0xa140), ('902d','twod',0x902d)]
rust = ['//! Public method byte offsets and bounds. Generated by scripts/registers.py.', '#[derive(Debug, Clone, Copy)]', 'pub struct Method { pub class: u32, pub offset: u32, pub count: u32, pub stride: u32, pub name: &\'static str }', 'pub const METHODS: &[Method] = &[']
doc = ['# Method register reference', '', 'Offsets are **bytes**, not FIFO word indices. Array counts are backend limits.', 'This is a register-file catalogue, not a claim that every mode executes on Metal.', 'Unimplemented effects are rejected. Fields and enums are defined by the linked public symbol.', '', '| Class | Byte offset | Count / stride | Public symbol |', '| --- | --- | --- | --- |']
for cl, folder, ident in specs:
 text = (root/f'target/reference/cl{cl}.h').read_text()
 for line in text.splitlines():
  m = re.fullmatch(r'#define NV\w+?_(\w+)(?:\(([ij])\))?\s+(0x[0-9a-f]{4}|\(0x[0-9a-f]{4}\+\([ij]\)\*\d+\))',line)
  if not m: continue
  name, arr, val = m.groups()
  if ident == 0xb197:
   words = ['COLOR_TARGET','ZT_','VIEWPORT','SCISSOR','VERTEX_ATTRIBUTE','VERTEX_STREAM','INDEX_BUFFER','BLEND','DEPTH','STENCIL','CULL','FRONT_FACE','POLYGON_MODE','PIPELINE_','PROGRAM_REGION','CONSTANT_BUFFER','TEX_HEADER_POOL','TEX_SAMPLER_POOL','CLEAR','CT_SELECT','Z_WRITE','BINDLESS_TEXTURE','GLOBAL_BASE_','COLOR_MASK']
   if not any(w in name for w in words) and name not in ['BEGIN','END','SET_VERTEX_ARRAY_START','DRAW_VERTEX_ARRAY','SET_SELECT_MAXWELL_TEXTURE_HEADERS']: continue
  off = int(re.search(r'0x[0-9a-f]+',val)[0],16)
  stride = int(re.search(r'\*(\d+)',val)[1]) if arr else 0
  count = (8 if ('COLOR_TARGET' in name or 'PER_TARGET' in name or 'COLOR_MASK' in name or name=='SET_BLEND') else 6 if 'PIPELINE_' in name else 5 if 'BIND_GROUP' in name else 4 if name=='SET_COLOR_CLEAR_VALUE' else 16) if arr else 1
  rust.append(f'    Method {{ class: 0x{ident:x}, offset: 0x{off:04x}, count: {count}, stride: {stride}, name: "{name}" }},')
  url=f'https://github.com/NVIDIA/open-gpu-doc/blob/{revision}/classes/{folder}/cl{cl}.h'
  doc.append(f'| {cl.upper()} | `0x{off:04x}` | {count} / {stride} | [`{name}`]({url}) |')
rust += ['];','pub fn lookup(class: u32, offset: u32) -> Option<&\'static Method> { METHODS.iter().find(|m| m.class == class && (offset == m.offset || (m.stride != 0 && offset >= m.offset && (offset-m.offset).is_multiple_of(m.stride) && (offset-m.offset)/m.stride < m.count))) }']
(root/'src/registers.rs').write_text('\n'.join(rust)+'\n')
(root/'REGISTERS.md').write_text('\n'.join(doc)+'\n')
